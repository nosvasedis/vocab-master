/* Spend ledger: every paid API call is recorded with its real token usage, and no job may start
   if its estimate would push a provider past its cap (content/pricing.json → caps).
   State lives in work/state/ledger.json (committed, no secrets); docs/roadmap/BUDGET.md is regenerated from it. */
import fs from "node:fs";
import path from "node:path";
import { ROOT } from "./env.mjs";

export const PRICING = JSON.parse(fs.readFileSync(path.join(ROOT, "content", "pricing.json"), "utf8"));

export class BudgetError extends Error {}

export function createLedger({ file = path.join(ROOT, "work", "state", "ledger.json"), caps = PRICING.caps, budgetDoc = path.join(ROOT, "docs", "roadmap", "BUDGET.md") } = {}) {
  const read = () => {
    try { return JSON.parse(fs.readFileSync(file, "utf8")); } catch { return { entries: [] }; }
  };
  const write = (data) => {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.tmp`;
    fs.writeFileSync(tmp, JSON.stringify(data, null, 2));
    fs.renameSync(tmp, file);
  };

  const spent = (provider) => read().entries.filter((e) => e.provider === provider).reduce((s, e) => s + (e.usd || 0), 0);
  const remaining = (provider) => (caps[provider] ?? 0) - spent(provider);

  return {
    spent,
    remaining,
    caps,
    /** Throws BudgetError when `estimateUsd` would exceed the provider's cap. */
    assertCanSpend(provider, estimateUsd, job = "") {
      const left = remaining(provider);
      if (estimateUsd > left + 1e-9) {
        throw new BudgetError(`${job || "Job"} would cost ~$${estimateUsd.toFixed(3)} but only $${Math.max(0, left).toFixed(3)} of the ${provider} cap ($${caps[provider]}) is left.`);
      }
      return left - estimateUsd;
    },
    record({ provider, model, mode = "standard", inTok = 0, outTok = 0, usd, job = "" }) {
      const data = read();
      const cost = usd ?? 0;
      data.entries.push({ t: new Date().toISOString(), provider, model, mode, inTok, outTok, usd: Number(cost.toFixed(6)), job });
      write(data);
      if (budgetDoc) writeBudgetDoc(budgetDoc, data, caps);
      return cost;
    },
    entries: () => read().entries,
  };
}

/** USD cost of a Gemini TTS call from token counts. */
export function geminiCost(model, { inTok = 0, outTok = 0, mode = "standard" } = {}) {
  const rate = PRICING.gemini[model]?.[mode];
  if (!rate) throw new Error(`No pricing for ${model} (${mode}) in content/pricing.json`);
  return (inTok * rate.in + outTok * rate.out) / 1e6;
}

/** USD cost of a direct DeepSeek text call from token counts. */
export function deepseekCost(model, { inTok = 0, outTok = 0 } = {}) {
  const rate = PRICING.deepseek?.[model]?.standard;
  if (!rate) throw new Error(`No pricing for ${model} in content/pricing.json`);
  return (inTok * rate.in + outTok * rate.out) / 1e6;
}

/** Estimated USD for `seconds` of Gemini TTS audio plus `inTok` input tokens. */
export function estimateGeminiTts(model, seconds, { inTok = 0, mode = "batch" } = {}) {
  return geminiCost(model, { inTok, outTok: seconds * PRICING.audioTokensPerSecond, mode });
}

function writeBudgetDoc(file, data, caps) {
  const by = {};
  for (const e of data.entries) {
    const k = `${e.provider}|${e.model}|${e.mode}`;
    by[k] ||= { ...e, usd: 0, inTok: 0, outTok: 0, calls: 0 };
    by[k].usd += e.usd; by[k].inTok += e.inTok; by[k].outTok += e.outTok; by[k].calls += 1;
  }
  const providers = [...new Set([...Object.keys(caps), ...data.entries.map((e) => e.provider)])];
  const lines = [
    "# Budget",
    "",
    "_Generated by `scripts/lib/ledger.mjs` from `work/state/ledger.json` — do not edit by hand._",
    "",
    "| Provider | Cap (USD) | Spent | Left |",
    "|---|---|---|---|",
    ...providers.map((p) => {
      const s = data.entries.filter((e) => e.provider === p).reduce((a, e) => a + e.usd, 0);
      return `| ${p} | ${caps[p] ?? "—"} | ${s.toFixed(3)} | ${caps[p] != null ? (caps[p] - s).toFixed(3) : "—"} |`;
    }),
    "",
    "| Provider | Model | Mode | Calls | In tokens | Out tokens | USD |",
    "|---|---|---|---|---|---|---|",
    ...Object.values(by).map((r) => `| ${r.provider} | ${r.model} | ${r.mode} | ${r.calls} | ${r.inTok} | ${r.outTok} | ${r.usd.toFixed(4)} |`),
    "",
  ];
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, lines.join("\n"));
}
