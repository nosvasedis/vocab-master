#!/usr/bin/env node
/* Builds content/visual-lexicon.json: concrete, picturable nouns. The lesson validator uses it to enforce
   "show what you say" — any of these nouns mentioned in a line must be visible (character, prop or focus word).
   Source: single-word nouns from the CPP word bank, minus abstract words, plus everyday objects. */
import fs from "node:fs";
import path from "node:path";
import { ROOT } from "../lib/env.mjs";
import { CPP_WORDBANK } from "../../desktop/renderer/coursebook-data.js";

const ABSTRACT = new Set(`oracy presentation text life story type setting idea thing way time day week month year
name word words question answer problem rule rules reason fact information opinion feeling feelings
fun help job work chore chores meaning sentence paragraph topic theme culture tradition history future past
present moment minute hour second morning afternoon evening night weekend holiday vacation trip journey
adventure experience memory dream plan project lesson skill knowledge kindness friendship health safety
energy power peace freedom choice change difference challenge goal success mistake luck surprise
weather nature environment community neighborhood neighbourhood society country world space place area
part piece kind sort side end start beginning middle top bottom number amount group team class
language english greek music art science math maths sport sports game games hobby interest
voice sound noise smell taste touch sight hearing body mind heart brain idea ideas favorite favourite
partner people person everyone someone nothing something anything thing things lot
show play watch cook walk ride drink swing jump run call visit rest dance sleep kiss hug smile laugh wave look turn stop lift fall back light mean match fly swim race practice sign train
can will may must friend friends sunny ground air hero paint hand hands eye eyes ear ears head arm arms leg legs foot feet hair face nose mouth`.split(/\s+/).filter(Boolean));

const EVERYDAY = `hat cap scarf glove gloves coat jacket shirt t-shirt dress skirt trousers jeans shoe shoes boot boots sock socks
photo picture camera phone computer tablet book books notebook pen pencil crayon ruler bag backpack box ball kite doll teddy
car bus bike bicycle train plane boat ship truck tractor rocket door window table chair sofa bed lamp clock cup plate bowl
spoon fork knife glass bottle cake bread apple banana orange milk water juice egg cheese pizza sandwich soup ice-cream
tree flower flowers grass leaf leaves sun moon star stars cloud rain snow river lake sea beach mountain hill garden park
dog cat bird fish horse cow sheep chicken duck rabbit mouse frog bee butterfly owl lion tiger elephant monkey bear
house home school shop market street road bridge tower castle tent letter card present gift balloon candle umbrella
key map money coin ticket guitar drum piano violin trumpet whistle flag poster board desk bin`.split(/\s+/).filter(Boolean);

const nouns = new Set(EVERYDAY);
for (const w of CPP_WORDBANK) {
  const t = String(w.type || "").trim();
  const e = w.english.trim().toLowerCase();
  if (!/^n\.?$/.test(t) || /\s/.test(e) || e.length < 3 || ABSTRACT.has(e)) continue;
  nouns.add(e);
}
for (const a of ABSTRACT) nouns.delete(a);
const out = { _note: "Generated by scripts/lessons/build-lexicon.mjs — picturable nouns the validator requires to be visible.", nouns: [...nouns].sort() };
fs.writeFileSync(path.join(ROOT, "content", "visual-lexicon.json"), JSON.stringify(out, null, 0) + "\n");
console.log(`${out.nouns.length} picturable nouns`);
